<?php

namespace Modules\Product\Support;

class ChannelSku
{

    public static function normalize($value, ?string $externalProductId = null): ?string
    {
        $sku = trim((string) ($value ?? ''));

        if ($sku === '' || preg_match('/[\p{L}\p{N}]/u', $sku) !== 1) {
            return null;
        }

        if (self::isAutoGenerated($sku, $externalProductId)) {
            return null;
        }

        return $sku;
    }

    public static function isPlaceholder($value, ?string $externalProductId = null): bool
    {
        return self::normalize($value, $externalProductId) === null;
    }

    public static function reason($value, ?string $externalProductId = null): ?string
    {
        $sku = trim((string) ($value ?? ''));

        if ($sku === '') {
            return 'Model tidak punya SKU di channel — isi SKU di Seller Center agar bisa dipetakan.';
        }

        if (preg_match('/[\p{L}\p{N}]/u', $sku) !== 1) {
            return 'SKU model hanya berisi tanda baca ("' . $sku . '") — isi SKU asli di Seller Center agar bisa dipetakan.';
        }

        if (self::isAutoGenerated($sku, $externalProductId)) {
            return 'SKU model dibuat otomatis marketplace ("' . $sku . '") karena kosong di Seller Center — isi SKU asli agar bisa dipetakan.';
        }

        return null;
    }

    private static function isAutoGenerated(string $sku, ?string $externalProductId): bool
    {
        $listingId = trim((string) $externalProductId);

        if ($listingId === '') {
            return false;
        }

        return preg_match('/^' . preg_quote($listingId, '/') . '-[\d-]+$/', $sku) === 1;
    }
}
